// Bundles _ontwerp/avatars/*/*.svg into avatars.js (run: node tools/build-avatars.js).
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', '_ontwerp', 'avatars');
const SPECIES = { kat: 'kat', hond: 'hond', konijn: 'konijn' };
const NAMES = {};
const out = {};
Object.keys(SPECIES).forEach(function (dir) {
  fs.readdirSync(path.join(root, dir)).filter(function (f) { return /\.svg$/.test(f); }).sort().forEach(function (f) {
    const id = f.replace(/\.svg$/, '').split('-').slice(2).join('-');
    let s = fs.readFileSync(path.join(root, dir, f), 'utf8');
    s = s.replace(/<title>[\s\S]*?<\/title>/, '').replace(/<desc>[\s\S]*?<\/desc>/, '')
      .replace(/\s+xmlns:inkscape="[^"]*"/, '').replace(/\s+inkscape:label="[^"]*"/g, '')
      .replace(/<svg[^>]*>/, '<svg viewBox="0 0 600 760" xmlns="http://www.w3.org/2000/svg">')
      .replace(/>\s+</g, '><').replace(/\s+/g, ' ').trim();
    const fur = (s.match(new RegExp('id="' + id + '-fur"[^>]*><stop[^>]*stop-color="([^"]+)"[^>]*/><stop[^>]*stop-color="([^"]+)"[^>]*/><stop[^>]*stop-color="([^"]+)"')) || []);
    out[id] = { species: dir, name: id.charAt(0).toUpperCase() + id.slice(1), fur: [fur[1], fur[2], fur[3]], svg: s };
  });
});
const order = ['tango', 'smudge', 'poppy', 'miko', 'nimbus', 'honey', 'pepper', 'sunny', 'miso', 'pickle', 'pip', 'hazel', 'mochi', 'clover', 'juniper'];
let js = '(function () {\n  \'use strict\';\n  var LC = (window.LC = window.LC || {});\n  // Generated by tools/build-avatars.js - do not edit by hand.\n  LC.AVATAR_ORDER = ' + JSON.stringify(order) + ';\n  LC.AVATARS = {\n';
js += order.map(function (id) { return '    ' + id + ': ' + JSON.stringify(out[id]); }).join(',\n') + '\n  };\n})();\n';
fs.writeFileSync(path.join(__dirname, '..', 'avatars.js'), js);
console.log('avatars.js', (js.length / 1024).toFixed(0) + ' KB', order.map(function (i) { return i + ':' + (out[i] ? out[i].fur.join('/') : 'MISSING'); }).join(' '));
